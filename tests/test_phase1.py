"""Phase 1 tests: filtering and fingerprinting. Each test builds a tiny fake repository."""
import os
from pathlib import Path

import pytest
from helpers import write

from repo_analyzer import FilterOptions, filter_repo
from repo_analyzer.phase1_filter import read_text


def kept(result) -> set[str]:
    return {e.path for e in result.files}


def reasons(result) -> dict[str, str]:
    return {s.path: s.reason for s in result.skipped}


# --------------------------------------------------------------------------- #
# What gets skipped, and why
# --------------------------------------------------------------------------- #
def test_default_directories_are_skipped_with_reasons(tmp_path):
    for rel in (".git/config", "__pycache__/a.pyc", "build/x.py", "node_modules/pkg/i.js", "src/app.py"):
        write(tmp_path, rel, "x = 1\n")
    r = filter_repo(tmp_path)
    assert kept(r) == {"src/app.py"}
    assert reasons(r) == {".git/": "ignored_dir", "__pycache__/": "ignored_dir",
                          "build/": "ignored_dir", "node_modules/": "vendor"}


def test_a_skipped_folder_counts_once_not_per_file(tmp_path):
    for i in range(20):
        write(tmp_path, f"vendor/lib/f{i}.py", "x = 1\n")
    write(tmp_path, "main.py", "x = 1\n")
    r = filter_repo(tmp_path)
    assert r.skipped_counts == {"vendor": 1}


def test_root_and_nested_gitignore(tmp_path):
    write(tmp_path, ".gitignore", "out/\n*.log\n")
    write(tmp_path, "sub/.gitignore", "secret_dir/\n")
    for rel in ("out/a.py", "run.log", "sub/keep.py", "sub/secret_dir/h.py", "sub/other.log", "top.py"):
        write(tmp_path, rel, "x = 1\n")
    r = filter_repo(tmp_path)
    assert kept(r) == {".gitignore", "sub/.gitignore", "sub/keep.py", "top.py"}
    assert reasons(r)["out/"] == "gitignored" and reasons(r)["sub/secret_dir/"] == "gitignored"
    assert reasons(r)["run.log"] == "gitignored" and reasons(r)["sub/other.log"] == "gitignored"


def test_nested_gitignore_is_scoped_to_its_own_folder(tmp_path):
    """An anchored rule ('/only_here.py') in sub/.gitignore means sub/only_here.py, nothing else."""
    write(tmp_path, "sub/.gitignore", "/only_here.py\n")
    for rel in ("only_here.py", "sub/only_here.py", "sub/deeper/only_here.py", "other/only_here.py"):
        write(tmp_path, rel, "x = 1\n")
    r = filter_repo(tmp_path)
    assert reasons(r) == {"sub/only_here.py": "gitignored"}
    assert {"only_here.py", "sub/deeper/only_here.py", "other/only_here.py"} <= kept(r)


def test_gitignore_can_be_turned_off(tmp_path):
    write(tmp_path, ".gitignore", "ignored.py\n")
    write(tmp_path, "ignored.py", "x = 1\n")
    assert "ignored.py" in kept(filter_repo(tmp_path, FilterOptions(use_gitignore=False)))


def test_analyzerignore_file_and_extra_patterns(tmp_path):
    write(tmp_path, ".analyzerignore", "legacy/\n")
    for rel in ("legacy/old.py", "docs/conf.py", "app.py"):
        write(tmp_path, rel, "x = 1\n")
    r = filter_repo(tmp_path, FilterOptions(extra_ignore=("docs/",)))
    assert kept(r) == {".analyzerignore", "app.py"}
    assert reasons(r) == {"legacy/": "user_ignored", "docs/": "user_ignored"}


def test_virtualenv_is_found_by_marker_file_whatever_its_name(tmp_path):
    write(tmp_path, "myenv/pyvenv.cfg", "home = /usr/bin\n")
    write(tmp_path, "myenv/lib/site.py", "x = 1\n")
    write(tmp_path, ".venv/lib/x.py", "x = 1\n")
    write(tmp_path, "env/real_code.py", "x = 1\n")      # a folder NAMED env is not automatically a venv
    r = filter_repo(tmp_path)
    assert reasons(r) == {"myenv/": "virtualenv", ".venv/": "virtualenv"}
    assert "env/real_code.py" in kept(r)


def test_vendored_and_nested_git_repositories(tmp_path):
    write(tmp_path, "third_party/lib/a.py", "x = 1\n")
    write(tmp_path, "deps/other/.git", "gitdir: ../../.git/modules/other\n")   # submodule marker file
    write(tmp_path, "deps/other/b.py", "x = 1\n")
    write(tmp_path, "main.py", "x = 1\n")
    r = filter_repo(tmp_path)
    assert kept(r) == {"main.py"}
    assert reasons(r)["third_party/"] == "vendor" and reasons(r)["deps/other/"] == "nested_repo"


def test_binary_files_by_extension_and_by_content(tmp_path):
    write(tmp_path, "logo.png", b"\x89PNG....")
    write(tmp_path, "weird.py", b"\x00\x01\x02 not text")      # NUL bytes: binary even though it says .py
    write(tmp_path, "notes.txt", "plain text\n")
    r = filter_repo(tmp_path)
    assert kept(r) == {"notes.txt"}
    assert reasons(r) == {"logo.png": "binary", "weird.py": "binary"}


def test_generated_files_by_name_and_by_header(tmp_path):
    write(tmp_path, "api_pb2.py", "x = 1\n")
    write(tmp_path, "static/app.min.js", "var a=1;")
    write(tmp_path, "gen1.py", "# Generated by the protocol buffer compiler.  DO NOT EDIT!\nx = 1\n")
    write(tmp_path, "gen2.go", "// Code generated by mockgen. DO NOT EDIT.\npackage x\n")
    write(tmp_path, "README.md", "This page was generated by Sphinx.\n")           # prose: never flagged
    write(tmp_path, "late.py", "\n\n\n\n\n\n# generated by hand later\nx = 1\n")     # beyond the first 5 lines
    r = filter_repo(tmp_path)
    assert {p for p, why in reasons(r).items() if why == "generated"} == {
        "api_pb2.py", "static/app.min.js", "gen1.py", "gen2.go"}
    assert {"README.md", "late.py"} <= kept(r)


def test_too_large_files(tmp_path):
    write(tmp_path, "big.py", "x = 1\n" * 100)
    write(tmp_path, "small.py", "x = 1\n")
    r = filter_repo(tmp_path, FilterOptions(max_bytes=50))
    assert kept(r) == {"small.py"} and reasons(r) == {"big.py": "too_large"}


def test_symlinks_are_never_followed_even_loops(tmp_path):
    write(tmp_path, "real/a.py", "x = 1\n")
    try:
        os.symlink(tmp_path / "real" / "a.py", tmp_path / "link_to_file.py")
        os.symlink(tmp_path, tmp_path / "real" / "loop")               # points back at the root
    except OSError as exc:
        pytest.skip(f"this machine cannot create symlinks: {exc}")
    r = filter_repo(tmp_path)
    assert kept(r) == {"real/a.py"}
    assert reasons(r) == {"link_to_file.py": "symlink", "real/loop/": "symlink"}


@pytest.mark.skipif(
    os.name == "nt" or getattr(os, "geteuid", lambda: -1)() == 0,
    reason="POSIX-only permission model; root can read everything",
)
def test_unreadable_file(tmp_path):
    p = write(tmp_path, "secret.py", "x = 1\n")
    p.chmod(0)
    try:
        assert reasons(filter_repo(tmp_path)) == {"secret.py": "unreadable"}
    finally:
        p.chmod(0o644)


