def test_skipped_list_is_capped_but_counts_stay_exact(tmp_path):
    write(tmp_path, ".gitignore", "*.tmp\n")
    for i in range(30):
        write(tmp_path, f"f{i}.tmp", "x")
    r = filter_repo(tmp_path, FilterOptions(max_skipped_listed=5))
    assert len(r.skipped) == 5 and r.skipped_counts["gitignored"] == 30
    assert any("truncated" in w for w in r.warnings)


def test_non_utf8_gitignore_does_not_crash(tmp_path):
    write(tmp_path, ".gitignore", "caf\xe9/\n".encode("latin-1"))
    write(tmp_path, "a.py", "x = 1\n")
    assert "a.py" in kept(filter_repo(tmp_path))


def test_empty_repo_and_bad_root(tmp_path):
    assert any("No files" in w for w in filter_repo(tmp_path).warnings)
    with pytest.raises(NotADirectoryError):
        filter_repo(tmp_path / "does_not_exist")


def test_result_records_size_hash_suffix_and_read_text(tmp_path):
    write(tmp_path, "Mod.PY", "x = 1\n")
    r = filter_repo(tmp_path)
    e = r.files[0]
    assert (e.path, e.size, e.suffix, len(e.sha256)) == ("Mod.PY", 6, ".py", 64)   # suffix is lower-cased
    assert read_text(tmp_path, "Mod.PY") == "x = 1\n" and r.total_bytes == 6
