def make_repo(root: Path, order: list[str]) -> None:
    for rel in order:
        write(root, rel, f"# {rel}\n")


def test_fingerprint_is_stable_and_order_independent(tmp_path):
    a, b = tmp_path / "a", tmp_path / "b"
    make_repo(a, ["x.py", "pkg/y.py", "z.txt"])
    make_repo(b, ["z.txt", "pkg/y.py", "x.py"])
    assert filter_repo(a).fingerprint == filter_repo(a).fingerprint == filter_repo(b).fingerprint


def test_fingerprint_changes_when_kept_content_or_name_changes(tmp_path):
    write(tmp_path, "a.py", "x = 1\n")
    before = filter_repo(tmp_path).fingerprint
    write(tmp_path, "a.py", "x = 2\n")
    changed = filter_repo(tmp_path).fingerprint
    (tmp_path / "a.py").rename(tmp_path / "b.py")
    assert len({before, changed, filter_repo(tmp_path).fingerprint}) == 3


def test_fingerprint_ignores_skipped_files(tmp_path):
    write(tmp_path, ".gitignore", "cache/\n")
    write(tmp_path, "a.py", "x = 1\n")
    write(tmp_path, "cache/data.py", "v1\n")
    before = filter_repo(tmp_path).fingerprint
    write(tmp_path, "cache/data.py", "v2\n")
    assert filter_repo(tmp_path).fingerprint == before


